CREATE TABLE trade_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market VARCHAR(8) NOT NULL,
    symbol VARCHAR(24) NOT NULL,
    side VARCHAR(8) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    limit_price NUMERIC(20, 6) NOT NULL CHECK (limit_price > 0),
    currency VARCHAR(8) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('SIMULATED')),
    idempotency_key UUID NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_trade_order_created_at ON trade_order (created_at DESC);
CREATE TABLE risk_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(48) NOT NULL,
    severity VARCHAR(16) NOT NULL,
    detail TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE market_signal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market VARCHAR(8) NOT NULL,
    symbol VARCHAR(24) NOT NULL,
    signal VARCHAR(8) NOT NULL CHECK (signal IN ('BUY', 'SELL', 'HOLD')),
    confidence NUMERIC(6, 5) NOT NULL CHECK (confidence >= 0 AND confidence <= 1),
    source VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
