CREATE TABLE paper_fill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES trade_order(id),
    fill_key UUID NOT NULL UNIQUE,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    fill_price NUMERIC(20, 6) NOT NULL CHECK (fill_price > 0),
    filled_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_paper_fill_order_time ON paper_fill (order_id, filled_at);

CREATE TABLE paper_position (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market VARCHAR(2) NOT NULL,
    symbol VARCHAR(24) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity >= 0),
    average_cost NUMERIC(20, 6) NOT NULL CHECK (average_cost >= 0),
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_paper_position_instrument UNIQUE (market, symbol, currency)
);
